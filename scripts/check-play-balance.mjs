import assert from 'node:assert/strict';
import {checkPlay,recordPlay,loadBalance,mergeBalance,importBalance,PLAY_BALANCE_KEY,validateBalance} from '../platform/play-balance.js';
const data=new Map();
const storage={getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)};
const games={};
const records={platform:{profiles:{tae:{games},se:{games:{}}}}};
const add=(id,correct=true,assisted=false)=>{games['math-g1']={records:{...(games['math-g1']?.records||{}),[id]:{attempts:[{correct,assisted,at:1}]}}};};
assert.equal(checkPlay('tae',{storage,records}).allowed,true);
recordPlay('tae',{storage,records});
assert.equal(checkPlay('tae',{storage,records}).allowed,false);
assert.throws(()=>recordPlay('tae',{storage,records}),/새로운 문제/);
add('q1',false);
assert.equal(checkPlay('tae',{storage,records}).allowed,true,'Even a wrong answer is learning effort');
recordPlay('tae',{storage,records});
assert.equal(checkPlay('tae',{storage,records}).allowed,false);
add('q1',true,true);
assert.equal(checkPlay('tae',{storage,records}).allowed,false);
add('q1');
assert.equal(checkPlay('tae',{storage,records}).allowed,false);
assert.equal(checkPlay('se',{storage,records}).allowed,true);
add('q2');
recordPlay('tae',{storage,records});
const remote=mergeBalance(loadBalance(storage),{version:1,profiles:{tae:{plays:4,consumed:['math-g1:q3']},se:{plays:0,consumed:[]}}});
assert.equal(remote.profiles.tae.plays,4);
assert.deepEqual(remote.profiles.tae.consumed,['math-g1:q1','math-g1:q2','math-g1:q3']);
assert.deepEqual(mergeBalance(remote,remote),remote);
assert.deepEqual(importBalance(remote,{storage}),remote);
assert.throws(()=>validateBalance({...remote,profiles:{...remote.profiles,tae:{plays:1,consumed:['bad','bad']}}}));
assert.ok(data.has(PLAY_BALANCE_KEY));
console.log('PASS play balance: interleave, assisted exclusion, sibling separation, merge, validation');
