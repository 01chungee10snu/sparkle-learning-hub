import assert from 'node:assert/strict';
import * as Resources from '../platform/resource-economy.js';
import {FIRST_VISIT_REWARDS} from '../platform/first-visit-rewards.js';

const entries=new Map();
const storage={getItem:key=>entries.get(key)??null,setItem:(key,value)=>entries.set(key,String(value))};
globalThis.localStorage=storage;
const catalog=[];
const initial=Resources.exportResources();
assert.equal(initial.version,1);
assert.deepEqual(initial.profiles.tae.visitBonuses,{});
assert.equal(Resources.awardFirstVisit('home','tae',storage).locationId,'home');
assert.equal(Resources.awardFirstVisit('home','tae',storage),null);
assert.equal(Resources.awardFirstVisit('home','se',storage).locationId,'home');
assert.equal(Resources.wallet(catalog,'tae').available.math,1);
assert.equal(Resources.wallet(catalog,'se').available.math,1);
for(const id of Object.keys(FIRST_VISIT_REWARDS))Resources.awardFirstVisit(id,'tae',storage);
assert.equal(Object.keys(Resources.exportResources().profiles.tae.visitBonuses).length,Object.keys(FIRST_VISIT_REWARDS).length);
const before=Resources.exportResources();
const earlier=structuredClone(before);
earlier.profiles.tae.visitBonuses.home.at-=1;
Resources.importResources(earlier,storage);
assert.equal(Resources.exportResources().profiles.tae.visitBonuses.home.at,earlier.profiles.tae.visitBonuses.home.at);
Resources.importResources(before,storage);
assert.equal(Resources.exportResources().profiles.tae.visitBonuses.home.at,earlier.profiles.tae.visitBonuses.home.at);
assert.equal(Resources.wallet(catalog,'tae').uniqueCorrect,0);
assert.equal(Resources.wallet(catalog,'tae').fish.find(species=>species.id==='humpback-whale').canAdopt,false);
const tampered=structuredClone(before);
tampered.profiles.tae.visitBonuses.home.cost.math=500;
assert.throws(()=>Resources.importResources(tampered,storage),/영수증/);
const unknown=structuredClone(before);
unknown.profiles.tae.visitBonuses.forged={id:'forged',at:Date.now(),cost:{math:1,korean:0,english:0,hanja:0}};
assert.throws(()=>Resources.importResources(unknown,storage),/영수증|크기/);
assert.throws(()=>Resources.awardFirstVisit('forged','tae',storage),/장소/);
const legacy=structuredClone(before);
delete legacy.profiles.tae.visitBonuses;
delete legacy.profiles.se.visitBonuses;
const otherStorage={getItem:key=>key===Resources.RESOURCE_KEY?JSON.stringify(legacy):null,setItem(){}};
assert.deepEqual(Resources.loadResources(otherStorage).profiles.tae.visitBonuses,{});
console.log('PASS_FIRST_VISIT_V30: per-child one-time awards, reload, merge earliest, tamper checks, v1 compatibility and learning gates');
