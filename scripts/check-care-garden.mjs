import assert from 'node:assert/strict';
import {gardenSnapshot,mutateGarden} from '../magic-village-kma-v06/village/garden-state.js';
const memory=new Map(),storage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
let tests=0; const ok=(fn)=>{fn();tests++;};
const act=(extra)=>mutateGarden({who:'tae',area:'home',...extra},storage);
ok(()=>assert.equal(gardenSnapshot('tae','home',storage).plants.length,0));
ok(()=>assert.equal(act({action:'GARDEN_PLANT',slot:0,species:'flowers_pink'}).garden.plants[0].stage,0));
ok(()=>assert.equal(gardenSnapshot('se','home',storage).plants.length,0));
ok(()=>assert.throws(()=>act({action:'GARDEN_PLANT',slot:0,species:'tree_oak'})));
ok(()=>assert.throws(()=>act({action:'GARDEN_CARE',slot:0,care:'sun',expectedStage:0})));
for(const [expectedStage,care] of ['water','sun','song'].entries())ok(()=>assert.equal(act({action:'GARDEN_CARE',slot:0,care,expectedStage}).garden.plants[0].stage,expectedStage+1));
ok(()=>assert.throws(()=>act({action:'GARDEN_CARE',slot:0,care:'water',expectedStage:0})));
ok(()=>assert.equal(gardenSnapshot('tae','home',storage).plants[0].stage,3));
ok(()=>assert.throws(()=>act({action:'GARDEN_PLANT',slot:8,species:'tree_oak'})));
ok(()=>assert.throws(()=>act({action:'GARDEN_PLANT',slot:1,species:'__proto__'})));
ok(()=>mutateGarden({who:'tae',area:'plaza',action:'GARDEN_PLANT',slot:2,species:'tree_gold'},storage));
ok(()=>assert.equal(gardenSnapshot('se','plaza',storage).plants[0].species,'tree_gold'));
for(let i=0;i<6;i++)ok(()=>assert.equal(mutateGarden({who:'se',area:'plaza',action:'GARDEN_CARE',slot:2,care:['water','sun','song'][i%3],expectedStage:i},storage).garden.plants[0].stage,i+1));
ok(()=>assert.throws(()=>mutateGarden({who:'tae',area:'home',action:'GARDEN_PLANT',slot:1,species:'tree_oak'},{getItem:()=>null,setItem:()=>{throw Error('full')}})));
console.log('CARE_GARDEN_PASS '+tests+' checks');
